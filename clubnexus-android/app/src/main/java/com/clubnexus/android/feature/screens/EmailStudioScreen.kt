private val emailCategories = listOf("PERMISSION", "ANNOUNCEMENT", "REMINDER", "OTHER")
private val emailTones = listOf("Formal", "Semi-formal", "Friendly")

@Composable
fun EmailStudioScreen(api: ClubNexusApi, user: User) {
    val scope = rememberCoroutineScope()
    var members by remember { mutableStateOf<List<Member>>(emptyList()) }
    var logs by remember { mutableStateOf<List<EmailLog>>(emptyList()) }
    var settings by remember { mutableStateOf(EmailSettings()) }
    var category by remember { mutableStateOf("ANNOUNCEMENT") }
    var tone by remember { mutableStateOf("Semi-formal") }
    var subject by remember { mutableStateOf("") }
    var notes by remember { mutableStateOf("") }
    var body by remember { mutableStateOf("") }
    var external by remember { mutableStateOf("") }
    var selectedMemberIds by remember { mutableStateOf(setOf<String>()) }
    var aiGenerated by remember { mutableStateOf(false) }
    var busy by remember { mutableStateOf(false) }
    var error by remember { mutableStateOf<String?>(null) }
    var success by remember { mutableStateOf<String?>(null) }
    var expandedLog by remember { mutableStateOf<String?>(null) }
    LaunchedEffect(Unit) {
        runCatching { api.members() }.onSuccess { members = it }.onFailure { error = it.apiMessage() }
        runCatching { settings = api.emailSettings() }.onFailure { error = it.apiMessage() }
        runCatching { logs = api.emailLogs() }.onFailure { error = it.apiMessage() }
    }
    val memberRecipients = members.filter { it.id in selectedMemberIds }.map { it.user.email }
    val externalRecipients = external.split(',', ';', '\n', '\t', ' ').map { it.trim().lowercase() }.filter { it.isNotBlank() && it.contains('@') }
    val recipients = (memberRecipients + externalRecipients).distinct()
    ScreenFrame("Email Studio", "Generate club emails with AI, edit the draft, send through Gmail SMTP, and review delivery logs.", user) {
        ErrorMessage(error)
        success?.let { Text(it, color = MaterialTheme.colorScheme.primary) }
        InfoCard("Compose email") {
            ChoiceField("Category", category.displayCategory(), emailCategories.map { it.displayCategory() to it }) { value ->
                category = value
                if (value == "PERMISSION") {
                    tone = "Formal"
                    notes = "Club: ${settings.clubName}\nCollege: ${settings.collegeName}\nEvent name:\nDate:\nVenue:\nExpected participants:"
                    if (settings.hodEmail.isNotBlank()) external = settings.hodEmail
                }
            }
            ChoiceField("Tone", tone, emailTones.map { it to it }) { tone = it }
            OutlinedTextField(subject, { subject = it }, Modifier.fillMaxWidth(), label = { Text("Subject") }, singleLine = true)
            Text("Members", style = MaterialTheme.typography.labelLarge, fontWeight = FontWeight.SemiBold)
            if (members.isEmpty()) EmptyMessage("No members available.")
            members.forEach { member ->
                Row(Modifier.fillMaxWidth(), verticalAlignment = Alignment.CenterVertically) {
                    Checkbox(checked = member.id in selectedMemberIds, onCheckedChange = { checked -> selectedMemberIds = if (checked) selectedMemberIds + member.id else selectedMemberIds - member.id })
                    Column {
                        Text(member.user.name)
                        Text(member.user.email, style = MaterialTheme.typography.bodySmall, color = MaterialTheme.colorScheme.onSurfaceVariant)
                    }
                }
            }
            OutlinedTextField(external, { external = it }, Modifier.fillMaxWidth(), label = { Text("External emails") }, placeholder = { Text("hod@college.edu, guest@example.com") })
            OutlinedTextField(notes, { notes = it }, Modifier.fillMaxWidth(), label = { Text("Key points / notes") }, minLines = 3)
            if (user.role != "VIEWER") {
                Button(enabled = !busy && subject.isNotBlank() && notes.isNotBlank(), onClick = { scope.launch {
                    busy = true; error = null; success = null
                    runCatching { api.generateEmail(GenerateEmailRequest(category, subject.trim(), notes, tone, notes)).body }
                        .onSuccess { body = it; aiGenerated = true; success = "Email draft generated." }
                        .onFailure { error = it.apiMessage() }
                    busy = false
                } }, modifier = Modifier.fillMaxWidth()) { Text(if (busy) "Generating…" else "✦  Generate with AI") }
            }
            OutlinedTextField(body, { body = it; aiGenerated = false }, Modifier.fillMaxWidth(), label = { Text("Editable email body") }, minLines = 8)
            if (recipients.isNotEmpty()) Text("To: ${recipients.joinToString()}", style = MaterialTheme.typography.bodySmall, color = MaterialTheme.colorScheme.onSurfaceVariant)
            if (user.role != "VIEWER") Button(enabled = !busy && recipients.isNotEmpty() && subject.isNotBlank() && body.isNotBlank(), onClick = { scope.launch {
                busy = true; error = null; success = null
                runCatching { api.sendEmail(SendEmailRequest(subject.trim(), body, recipients, category, aiGenerated)) }
                    .onSuccess { result ->
                        val accepted = result.providerResult?.accepted?.size ?: recipients.size
                        success = "${result.message} to $accepted recipient${if (accepted == 1) "" else "s"}."
                        subject = ""; body = ""; notes = ""; aiGenerated = false
                        runCatching { logs = api.emailLogs() }
                    }
                    .onFailure { error = it.apiMessage(); runCatching { logs = api.emailLogs() } }
                busy = false
            } }, modifier = Modifier.fillMaxWidth()) { Text(if (busy) "Sending…" else "Send email") }
            if (recipients.isEmpty()) Text("Select at least one member or enter an external email address.", style = MaterialTheme.typography.bodySmall, color = MaterialTheme.colorScheme.onSurfaceVariant)
        }
        InfoCard("Email logs") {
            if (logs.isEmpty()) EmptyMessage("No email activity recorded yet.")
            logs.forEach { log ->
                Card(onClick = { expandedLog = if (expandedLog == log.id) null else log.id }, modifier = Modifier.fillMaxWidth().padding(vertical = 3.dp), colors = CardDefaults.cardColors(containerColor = MaterialTheme.colorScheme.surfaceVariant)) {
                    Column(Modifier.padding(12.dp), verticalArrangement = Arrangement.spacedBy(4.dp)) {
                        Row(Modifier.fillMaxWidth(), horizontalArrangement = Arrangement.SpaceBetween) { Text(log.subject, Modifier.weight(1f), fontWeight = FontWeight.SemiBold); Text(log.status, color = if (log.status == "SENT") MaterialTheme.colorScheme.primary else MaterialTheme.colorScheme.error) }
                        Text("${log.recipients.joinToString()} • ${log.sentAt.toDisplayDate()}", style = MaterialTheme.typography.bodySmall, color = MaterialTheme.colorScheme.onSurfaceVariant)
                        Text("${log.category.displayCategory()} • ${if (log.aiGenerated) "AI generated" else "Manual draft"}", style = MaterialTheme.typography.labelSmall)
                        if (expandedLog == log.id) Text(log.body, style = MaterialTheme.typography.bodySmall)
                    }
                }
            }
        }
    }
}

private fun String.displayCategory(): String = when (this) {
    "PERMISSION" -> "Permission Request"
    "ANNOUNCEMENT" -> "Announcement"
    "REMINDER" -> "Reminder"
    else -> "Custom"
}
